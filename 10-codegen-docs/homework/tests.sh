#!/usr/bin/env bash
# Прогоняет калькулятор на готовых входах и сверяет вывод (stdout и stderr вместе).
#   bash tests.sh [./calc]
export LC_ALL=C.UTF-8
CALC=${1:-./calc}
total=0
bad=0

# check "имя" "ввод (printf %b)" "ожидаемый вывод"
check() {
    local got rc
    total=$((total + 1))
    got=$(printf '%b' "$2" | "$CALC" 2>&1)
    rc=$?
    if [[ $got == "$3" && $rc -eq 0 ]]; then
        return
    fi
    bad=$((bad + 1))
    printf 'FAIL: %s (код %d)\n  ждали: %s\n  вышло: %s\n' "$1" "$rc" "${3//$'\n'/ | }" "${got//$'\n'/ | }"
}

# ok "имя" "условие в bash" — произвольная проверка
ok() {
    total=$((total + 1))
    if ! eval "$2"; then
        bad=$((bad + 1))
        printf 'FAIL: %s\n' "$1"
    fi
}

# --- считает и держит приоритеты
check "сумма и произведение" '2 + 3 * 4\n' '= 14'
check "скобки" '(2 + 3) * 4\n' '= 20'
check "вычитание слева направо" '10 - 4 - 3\n' '= 3'
check "дробные" '1.5 + 2.25\n10 / 4\n' $'= 3.75\n= 2.5'
check "деление без остатка" '1 / 3\n' '= 0.3333333333'
check "унарный минус" '-5 + 1\n' '= -4'
check "степень вправо" '2 ^ 3 ^ 2\n' '= 512'
check "степень выше минуса" '-2 ^ 2\n' '= -4'
check "степень с минусом" '2 ^ -1\n' '= 0.5'
check "остаток" '7 % 3\n' '= 1'
check "остаток и умножение слева направо" '2 * 3 % 4\n' '= 2'
check "остаток ниже степени" '2 + 7 % 4 ^ 2\n' '= 9'

# --- переменные
check "присваивание и чтение" $'x = 5\n2 * x\n' $'x = 5\n= 10'
check "переменная в своём присваивании" $'x = 5\nx = x + 1\nx\n' $'x = 5\nx = 6\n= 6'
check "несколько переменных" $'a = 2\nb = 3\na * b + a\n' $'a = 2\nb = 3\n= 8'
check "имя с подчёркиванием и цифрой" $'_v1 = 4\n_v1 * _v1\n' $'_v1 = 4\n= 16'

# --- функции
check "sqrt" 'sqrt(9)\n' '= 3'
check "sqrt в выражении" 'sqrt(16) + 2 * 3\n' '= 10'
check "вложенные функции" 'sqrt(abs(-16))\n' '= 4'
check "функция от переменной" $'x = 25\nsqrt(x)\n' $'x = 25\n= 5'
check "ln" 'ln(1)\n' '= 0'

# --- ошибки ввода: сообщение и дальше работаем
check "неопределённая переменная" $'y\n1 + 1\n' $'ошибка: переменная не определена: y\n= 2'
check "sqrt от отрицательного" $'sqrt(-1)\n2\n' $'ошибка: sqrt: аргумент -1 вне области определения\n= 2'
check "ln от нуля" 'ln(0)\n' 'ошибка: ln: аргумент 0 вне области определения'
check "неизвестная функция" 'foo(1)\n' 'ошибка: неизвестная функция: foo'
check "переменная как функция" $'x = 5\nx(2)\n' $'x = 5\nошибка: неизвестная функция: x'
check "2 + + 3" $'2 + + 3\n2 + 3\n' $'ошибка: синтаксическая ошибка\n= 5'
check "оборванное выражение" $'1 +\n2 + 2\n' $'ошибка: синтаксическая ошибка\n= 4'
check "скобка не закрыта" $'(1 + 2\n3\n' $'ошибка: синтаксическая ошибка\n= 3'
check "два числа подряд" '1 2\n' 'ошибка: синтаксическая ошибка'
check "присваивание числу" '5 = x\n' 'ошибка: синтаксическая ошибка'
check "чужой символ" '2 $ 3\n' 'ошибка: синтаксическая ошибка'
check "деление на ноль" '1 / 0\n' 'ошибка: деление на ноль'
check "остаток от нуля" '5 % 0\n' 'ошибка: деление на ноль'
check "деление на ноль не присваивает" $'x = 1 / 0\nx\n' $'ошибка: деление на ноль\nошибка: переменная не определена: x'
check "одна ошибка на строку" 'y + z\n' 'ошибка: переменная не определена: y'

# --- конец ввода и странный ввод
check "пустой ввод" '' ''
check "пустые строки" '\n\n' ''
check "EOF без перевода строки" '2 + 3' '= 5'
check "присваивание без перевода строки" 'x = 5' 'x = 5'
check "оборванное выражение в конце" '2 +' 'ошибка: синтаксическая ошибка'
check "перевод строки Windows" '2+2\r\n' '= 4'

long=$(head -c 100000 /dev/zero | tr '\0' a)
check "очень длинное имя" "$long\n1 + 1\n" $'ошибка: имя слишком длинное (максимум 31)\n= 2'
check "длинное имя в присваивании" "$long = 1\n1 + 1\n" $'ошибка: имя слишком длинное (максимум 31)\n= 2'
check "длинное имя функции" "$long(4)\n" 'ошибка: имя слишком длинное (максимум 31)'
digits=$(head -c 5000 /dev/zero | tr '\0' 9)
check "очень длинное число" "$digits + 1\n" '= inf'

# --- переполнение таблицы переменных
many=$(for i in $(seq 1 1100); do printf 'v%d = %d\n' "$i" "$i"; done)
ok "таблица переменных заполняется" \
    '[[ $(printf "%s\n" "$many" | "$CALC" 2>&1 | grep -c "таблица переменных заполнена") -eq 76 ]]'

# --- не падает на мусоре и глубоких скобках (код выхода меньше 128, нет сигнала)
deep=$(head -c 200000 /dev/zero | tr '\0' '(')
ok "глубокие скобки" 'printf "%s\n" "$deep" | "$CALC" >/dev/null 2>&1; (( $? < 128 ))'
ok "случайные байты" 'for i in 1 2 3 4 5; do head -c 65536 /dev/urandom | "$CALC" >/dev/null 2>&1; (( $? < 128 )) || exit 1; done'

if ((bad == 0)); then
    echo "tests.sh: все $total проверок прошли"
else
    echo "tests.sh: упало $bad из $total"
    exit 1
fi
