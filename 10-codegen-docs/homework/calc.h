/**
 * @file calc.h
 * @brief Общие функции калькулятора: ошибки, вывод, доступ к переменным и функциям.
 *
 * @mainpage Калькулятор на flex и bison
 *
 * Калькулятор читает строки со стандартного ввода и считает их.
 *
 * - `calc.l` — лексер (flex): разбивает текст на числа, имена и знаки.
 * - `calc.y` — грамматика (bison): собирает из токенов выражение и считает его.
 * - `calc.c` — ошибки, вывод, `main`; ::calc_lookup и ::calc_call вызываются из грамматики.
 * - `vars.h` — таблица переменных, `funcs.h` — встроенные функции.
 *
 * Приоритеты от низшего к высшему: `+ -`, затем `* / %`, затем унарный минус,
 * затем `^` (правая ассоциативность, `2 ^ 3 ^ 2` = 512, `-2 ^ 2` = -4).
 *
 * Строка вида `имя = выражение` записывает переменную. Ошибка в строке печатается
 * один раз в stderr, строка пропускается, программа идёт дальше.
 */
#ifndef CALC_H
#define CALC_H

#include <stdbool.h>

/**
 * @brief Печатает ошибку в stderr, но только первую в текущей строке.
 *
 * Формат как у printf. Строка после этого считается неудачной, пока не вызван
 * ::calc_end_line.
 * @param fmt формат сообщения
 */
void calc_fail(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

/**
 * @brief Была ли в текущей строке ошибка.
 * @return true, если ::calc_fail уже вызывали с начала строки
 */
bool calc_failed(void);

/** @brief Заканчивает строку: сбрасывает признак ошибки перед следующей. */
void calc_end_line(void);

/**
 * @brief Печатает результат выражения: `= значение`.
 * @param value значение
 */
void calc_print(double value);

/**
 * @brief Записывает переменную и печатает `имя = значение`.
 *
 * Если в строке уже была ошибка, ничего не делает. Отказ таблицы (она полна)
 * сообщает через ::calc_fail.
 * @param name  имя переменной
 * @param value значение
 */
void calc_assign(const char *name, double value);

/**
 * @brief Значение переменной.
 *
 * Если переменной нет, сообщает об ошибке через ::calc_fail и возвращает 0.
 * @param name имя переменной
 * @return значение или 0
 */
double calc_lookup(const char *name);

/**
 * @brief Вызывает функцию вида `имя(аргумент)`.
 *
 * Неизвестное имя и аргумент вне области определения сообщает через ::calc_fail
 * и возвращает 0.
 * @param name имя функции
 * @param arg  аргумент
 * @return результат или 0
 */
double calc_call(const char *name, double arg);

/**
 * @brief Сообщение разборщика bison об ошибке.
 * @param msg текст от bison, например "syntax error"
 */
void yyerror(const char *msg);

/** @brief Разборщик, создаёт bison (calc.tab.c). @return 0 при успехе */
int yyparse(void);

/** @brief Лексер, создаёт flex (lex.yy.c). @return код токена, 0 в конце ввода */
int yylex(void);

/** @brief Освобождает буферы лексера, создаёт flex. @return 0 */
int yylex_destroy(void);

#endif
