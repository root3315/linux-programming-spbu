/* shorten.h — сократить имя до 10 букв с многоточием.
 *
 * shorten_name() кладёт в буфер out имя name, сокращённое так, чтобы в нём
 * было не больше SHORT_NAME_MAX символов вместе с многоточием.
 *
 * Символ здесь — буква в UTF-8, а не байт: «Александрина» (12 букв,
 * 24 байта) и «Alexandrina» (11 букв, 11 байт) режутся одинаково, по буквам.
 * Многобайтовую букву функция пополам не режет. Битый UTF-8 не чинит, но
 * и не расширяет: байт, который не продолжает начатую букву, считается
 * отдельной буквой, поэтому буква всегда не длиннее 4 байт.
 *
 *   имя до 10 букв включительно  → копируется как есть
 *   имя длиннее 10 букв          → первые 9 букв + «…» (U+2026, 3 байта)
 *   name == NULL                 → как пустая строка
 *
 * cap — размер буфера в байтах. SHORT_NAME_CAP байт хватает всегда:
 * 9 букв по 4 байта + 3 байта многоточия + '\0' = 40.
 *
 * Возвращает:
 *    0  — имя скопировано без изменений
 *    1  — имя сокращено
 *   -1  — неправильные аргументы (out == NULL или cap == 0)
 *   -2  — результат не влез в буфер, в out пустая строка
 */
#ifndef SHORTEN_H
#define SHORTEN_H

#include <stddef.h>

#define SHORT_NAME_MAX 10
#define SHORT_NAME_CAP 40

int shorten_name(char *out, size_t cap, const char *name);

#endif /* SHORTEN_H */
